    tt = pg.eval_on_selector('.flb .flb-title', 'e=>{const c=getComputedStyle(e),r=e.getBoundingClientRect();return [c.fontSize,c.lineHeight,Math.round(r.left),Math.round(r.top)]}')
    check('mienne mobile : titre 16/20 en haut à gauche (centré dans la barre)', tt[:3] == ['16px', '20px', 20] and tt[3] in (18, 19))
    fx = pg.evaluate('(()=>{const f=document.querySelector(".flb"),v=f.querySelector(".flb-view").getBoundingClientRect(),c=f.querySelector(".flb-capm");return [getComputedStyle(f).backgroundColor,getComputedStyle(f.querySelector(".flb-t1")).backgroundColor,Math.round(v.left),Math.round(v.top),Math.round(innerWidth-v.right),c.hidden,c.textContent]})()')
