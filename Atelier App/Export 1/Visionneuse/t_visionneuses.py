    pg.mouse.move(640, 400); pg.wait_for_timeout(1500)
    check('f26 barres masquées après 1,2 s', 'oh' in pg.get_attribute('.lbx-f26', 'class'))
    pg.mouse.move(700, 420); pg.wait_for_timeout(150)
    pg.click('.lbx-f26 .f26-share'); pg.wait_for_timeout(100)
    check('f26 panneau Partager', pg.is_visible('.lbx-f26 .shp'))
    pg.screenshot(path=str(C / 'web_f26_share.jpg'), quality=80)
    pg.keyboard.press('Escape'); pg.keyboard.press('Escape'); pg.wait_for_timeout(100)
    check('f26 fermée (Échap)', not pg.is_visible('.lbx-f26'))
    check('?file= retiré', 'file=' not in pg.url)
    # dark
    pg.click('#themeBtn'); pg.click('.lbx-gallery img >> nth=2'); pg.wait_for_timeout(300)
    pg.screenshot(path=str(C / 'web_f26_sombre.jpg'), quality=80); pg.keyboard.press('Escape'); pg.click('#themeBtn')
    # oasis
    pg.select_option('.demo select', 'oasis'); pg.wait_for_timeout(50)
    pg.click('.lbx-gallery img >> nth=0'); pg.wait_for_timeout(300)
    check('oasis ouverte', pg.is_visible('.lbx-oasis .oa-modal'))
    bb = pg.eval_on_selector('.lbx-oasis .oa-modal', 'e=>[e.offsetWidth,e.offsetHeight]')
    check('oasis 1010x628', bb == [1010, 628])
    pg.screenshot(path=str(C / 'web_oasis.jpg'), quality=80)
    pg.mouse.click(1100, 350); pg.wait_for_timeout(100)
    check('oasis clic moitié droite → suivante', pg.inner_text('.lbx-oasis h1') == 'Example2.png')
    pg.keyboard.press('Escape'); pg.wait_for_timeout(50)
