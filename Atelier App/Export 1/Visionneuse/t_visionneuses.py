    pg.select_option('.demo select', 'mine')
    pg.click('.lbx-gallery img >> nth=1'); pg.wait_for_timeout(300)
    check('mienne ouverte', pg.is_visible('.flb'))
    pg.mouse.click(640, 400); pg.wait_for_timeout(450)
    check("mienne web : clic sur l'image ne ferme pas", pg.is_visible('.flb'))
