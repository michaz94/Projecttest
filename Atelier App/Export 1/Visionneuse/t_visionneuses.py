    check('mienne web : Échap ferme d\'abord la fenêtre infos', pg.is_visible('.flb') and not pg.is_visible('.flb .flb-dlg'))
    pg.mouse.click(30, 200); pg.wait_for_timeout(200)
    check('mienne web : clic dans le vide ferme', not pg.is_visible('.flb'))
    pg.click('.lbx-gallery img >> nth=1'); pg.wait_for_timeout(300)
    pg.screenshot(path=str(C / 'web_mine.jpg'), quality=80); pg.keyboard.press('Escape')
    pg.select_option('.demo select', 'f26')
    ctx.close()
    # ---------------- WEB sur téléphone (tactile, comme sa capture) ----------------
    ctx = b.new_context(viewport={'width': 412, 'height': 915}, device_scale_factor=2.625, is_mobile=True, has_touch=True); ctx.set_offline(True)
