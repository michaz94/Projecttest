    check('mienne mobile : ✕ rond', xr == '50%')
    pg.screenshot(path=str(C / 'mob_mine_seule.jpg'), quality=80)
    st = pg.eval_on_selector('.flb .flb-cnt', 'e=>[getComputedStyle(e).fontWeight,getComputedStyle(e).color]')
    check('mienne : chiffres gras #e6e6e6', st == ['700', 'rgb(230, 230, 230)'])
