    th = pg.eval_on_selector('.flb .flb-th:not(.on)', 'e=>{const c=getComputedStyle(e),i=getComputedStyle(e.querySelector("img"));return [i.width,i.borderTopWidth,c.backgroundColor,Math.round(document.querySelector(".flb .flb-th").getBoundingClientRect().left)]}')
