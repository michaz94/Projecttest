    b = p.chromium.launch()
    errs = []
    # ---------------- WEB ----------------
    ctx = b.new_context(viewport={'width': 1280, 'height': 800}); ctx.set_offline(True)
    pg = ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto((R / 'apercu-fandom-web.html').as_uri()); pg.wait_for_timeout(400)
    check('web: 11 images', pg.eval_on_selector_all('.mw-parser-output img', 'l=>l.length') == 11)
    check('web: sélecteur 3 options', pg.eval_on_selector_all('.demo select option', 'l=>l.length') == 3)
    check('web : « la mienne » par défaut', pg.eval_on_selector('.demo select', 'e=>e.value') == 'mine')
