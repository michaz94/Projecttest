    pg.select_option('.demo select', 'f26'); pg.wait_for_timeout(50)
    pg.click('#themeBtn'); pg.tap('.portable-infobox img'); pg.wait_for_timeout(3500)
    check('f26 tactile : barres épinglées', 'pinned' in pg.get_attribute('.lbx-f26', 'class') and 'oh' not in pg.get_attribute('.lbx-f26', 'class'))
    check('f26 tactile : cadenas caché', not pg.is_visible('.lbx-f26 .f26-pin'))
    pg.screenshot(path=str(C / 'web_f26_tactile.jpg'), quality=80)
    ctx.close()
    # ---------------- MOBILE ----------------
    dev = {k: v for k, v in p.devices['Pixel 7'].items() if k != 'default_browser_type'}
    ctx = b.new_context(**dev); ctx.set_offline(True)
    pg = ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto((R / 'apercu-fandom-mobile.html').as_uri()); pg.wait_for_timeout(400)
    check('mobile: sélecteurs', pg.eval_on_selector_all('select[data-lbx-select]', 'l=>l.length') == 2)
    check('mobile : « la mienne » par défaut', pg.eval_on_selector('select[data-lbx-select]', 'e=>e.value') == 'mine')
    pg.select_option('select[data-lbx-select] >> nth=0', 'fm25'); pg.wait_for_timeout(50)
    pg.tap('.portable-infobox img'); pg.wait_for_timeout(400)
