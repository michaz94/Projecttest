    # f26
    pg.click('.portable-infobox img'); pg.wait_for_timeout(300)
    check('f26 ouverte', pg.is_visible('.lbx-f26'))
    check('f26 titre', pg.inner_text('.lbx-f26 h1') == 'Example.jpg')
    check('f26 progression', 'de 11' in pg.inner_text('.lbx-f26 .f26-prog'))
    check('f26 ?file=', 'file=Example.jpg' in pg.url)
    check('f26 flèche précédente masquée au début', not pg.is_visible('.lbx-f26 .f26-arr.prev'))
    pg.screenshot(path=str(C / 'web_f26.jpg'), quality=80)
    pg.keyboard.press('ArrowRight'); pg.wait_for_timeout(100)
